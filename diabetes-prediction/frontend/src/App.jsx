import { useState } from "react";
import "./App.css";

const MODELS = {
  logistic: "Logistic Regression",
  decision_tree: "Decision Tree",
  random_forest: "Random Forest",
  knn: "K-Nearest Neighbors",
  svm: "Support Vector Machine",
  gradient_boosting: "Gradient Boosting",
  xgboost: "XGBoost",
};

const FIELDS = [
  { name: "Pregnancies", label: "Pregnancies" },
  { name: "Glucose", label: "Glucose" },
  { name: "BloodPressure", label: "Blood Pressure" },
  { name: "SkinThickness", label: "Skin Thickness" },
  { name: "Insulin", label: "Insulin" },
  { name: "BMI", label: "BMI", step: "0.1" },
  { name: "DiabetesPedigreeFunction", label: "Diabetes Pedigree Function", step: "0.01" },
  { name: "Age", label: "Age" },
];

const EMPTY_FORM = Object.fromEntries(FIELDS.map((f) => [f.name, ""]));

function App() {
  const [formData, setFormData] = useState(EMPTY_FORM);
  const [selectedModel, setSelectedModel] = useState("logistic");
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);

  const handleChange = (e) => {
    setFormData({ ...formData, [e.target.name]: e.target.value });
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setLoading(true);
    setResult(null);

    try {
      const numericFields = Object.fromEntries(
        Object.entries(formData).map(([key, value]) => [key, Number(value)])
      );

      const response = await fetch("http://127.0.0.1:5000/predict", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ model: selectedModel, ...numericFields }),
      });

      const data = await response.json();
      setResult(data);
    } catch (error) {
      setResult({ error: "Unable to connect to the prediction server." });
    }

    setLoading(false);
  };

  return (
    <div className="app">
      <header className="header">
        <h1>DiabetesPredict</h1>
        <p>Diabetes Risk Assessment</p>
      </header>

      <main className="main">
        <form className="card" onSubmit={handleSubmit}>
          <h2>Patient Information</h2>

          <div className="field">
            <label>Model</label>
            <select
              value={selectedModel}
              onChange={(e) => setSelectedModel(e.target.value)}
            >
              {Object.entries(MODELS).map(([value, label]) => (
                <option key={value} value={value}>{label}</option>
              ))}
            </select>
          </div>

          <div className="grid">
            {FIELDS.map((field) => (
              <div className="field" key={field.name}>
                <label>{field.label}</label>
                <input
                  type="number"
                  name={field.name}
                  step={field.step || "1"}
                  min="0"
                  required
                  value={formData[field.name]}
                  onChange={handleChange}
                />
              </div>
            ))}
          </div>

          <button type="submit" disabled={loading}>
            {loading ? "Analyzing..." : "Predict"}
          </button>
        </form>

        {result && !result.error && (
          <div className="card result">
            <h2 className={result.prediction === 1 ? "positive" : "negative"}>
              {result.result}
            </h2>

            <p>Model: {MODELS[selectedModel]}</p>
            <p>Risk Probability: {(result.probability * 100).toFixed(1)}%</p>

            <div className="progress-track">
              <div
                className="progress-fill"
                style={{ width: `${result.probability * 100}%` }}
              />
            </div>

            {result.metrics && (
              <div className="metrics">
                <div>
                  <strong>{result.metrics.accuracy}%</strong>
                  <span>Accuracy</span>
                </div>
                <div>
                  <strong>{result.metrics.precision}%</strong>
                  <span>Precision</span>
                </div>
                <div>
                  <strong>{result.metrics.recall}%</strong>
                  <span>Recall</span>
                </div>
                <div>
                  <strong>{result.metrics.f1}%</strong>
                  <span>F1 Score</span>
                </div>
              </div>
            )}

            <p className="note">
              This prediction is generated by a machine learning model for
              educational purposes only. It is not a medical diagnosis.
            </p>
          </div>
        )}

        {result?.error && <div className="card error">{result.error}</div>}
      </main>
    </div>
  );
}

export default App;